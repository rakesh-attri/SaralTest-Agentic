// Independent check of the Phase 4 exit criteria (PLAN.md §11):
//   pnpm validate:build [--root <path>] <buildRunId>…      specs exist, lint, typecheck, resolve; pass 2 settled
//   pnpm validate:build [--root <path>] --data <dataRunId>… data created, verified, cleaned, cleanup confirmed
// Re-parses every output with the Zod contracts and re-runs ESLint + `playwright test --list` itself (no trust in
// the build's own results). Executes no test.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { z } from 'zod';
import { runLint, runList } from '../src/agents/test-generator/toolchain.js';
import { AuditEntry, CleanupReport, DataPlan, NegativeOutcome, RecordVerification } from '../src/core/schemas/data.js';
import { ReviewFinding } from '../src/core/schemas/design.js';
import { DryRunReport, GeneratedArtifact } from '../src/core/schemas/generation.js';
import { TestCase } from '../src/core/schemas/testCase.js';

const args = process.argv.slice(2);
let root = resolve(import.meta.dirname, '..');
const runs: string[] = [];
let data = false;
for (let i = 0; i < args.length; i++) {
  const a = args[i] ?? '';
  if (a === '--root') root = resolve(args[++i] ?? '.');
  else if (a === '--data') data = true;
  else runs.push(a);
}
if (!runs.length) {
  process.stderr.write('usage: pnpm validate:build [--root <path>] [--data] <runId>…\n');
  process.exit(2);
}

const result = { failed: false };
const lines: string[] = [];
const ok = (m: string): void => {
  lines.push(`  ok   ${m}`);
};
const fail = (m: string): void => {
  result.failed = true;
  lines.push(`  FAIL ${m}`);
};
function parse<T>(file: string, schema: z.ZodType<T>): T | undefined {
  if (!existsSync(file)) {
    fail(`missing ${file}`);
    return undefined;
  }
  const r = schema.safeParse(JSON.parse(readFileSync(file, 'utf8')));
  if (!r.success) {
    fail(
      `${file}: ${r.error.issues
        .slice(0, 3)
        .map((i) => `${i.path.join('.')}: ${i.message}`)
        .join('; ')}`,
    );
    return undefined;
  }
  return r.data;
}
const sha16 = (s: string): string => createHash('sha256').update(s).digest('hex').slice(0, 16);

async function validateBuild(runId: string): Promise<void> {
  const dir = join(root, 'runs', runId, 'build');
  lines.push(`\n${runId} (${dir})`);
  const info = parse(
    join(dir, 'build-run.json'),
    z.looseObject({
      status: z.string(),
      buildEnvironment: z.string(),
      models: z.array(z.string()),
      designRunId: z.string().optional(),
      storyKey: z.string().optional(),
    }),
  );
  const manifest = parse(
    join(dir, 'manifest.json'),
    z.object({
      storyKey: z.string().optional(),
      designRun: z.string().optional(),
      artifacts: z.array(GeneratedArtifact),
    }),
  );
  const findings = parse(join(dir, 'review-pass2.json'), z.array(ReviewFinding));
  const dry = existsSync(join(dir, 'dry-run.json')) ? parse(join(dir, 'dry-run.json'), DryRunReport) : undefined;
  if (!info || !manifest || !findings) return;
  lines.push(
    `  labels: build ${info.buildEnvironment}, status ${info.status}, models ${info.models.join(', ') || 'none'}, dry-run ${dry ? `${dry.environment}/${dry.persona}` : 'none'}`,
  );

  // 1. Every APPROVED case of the design run has exactly one spec.
  const designRun = manifest.designRun ?? info.designRunId;
  const cases = designRun
    ? parse(join(root, 'runs', designRun, 'design', 'test-cases.json'), z.array(TestCase))
    : undefined;
  const specs = manifest.artifacts.filter((a) => a.kind === 'spec');
  if (cases) {
    const approved = cases.filter((c) => c.reviewStatus === 'APPROVED');
    const missing = approved.filter((c) => specs.filter((s) => s.testCaseIds.includes(c.id)).length !== 1);
    if (missing.length) fail(`APPROVED cases without exactly one spec: ${missing.map((c) => c.id).join(', ')}`);
    else ok(`${approved.length}/${approved.length} APPROVED cases of ${designRun} have one spec each`);
  } else fail('design run of the build is unknown');

  // 2. Files exist, carry the generated header, and match the recorded hash (no hand edits since the build).
  const files: string[] = [];
  for (const s of specs) {
    const f = join(root, ...s.path.split('/'));
    if (!existsSync(f)) {
      fail(`${s.path} missing`);
      continue;
    }
    const text = readFileSync(f, 'utf8');
    if (!/^\/\/ (Generated by sf-qa-agent|MECHANICAL skeleton)/.test(text)) fail(`${s.path}: no generated header`);
    if (sha16(text) !== s.hash) fail(`${s.path}: content differs from the build (hash ${sha16(text)} ≠ ${s.hash})`);
    files.push(s.path);
  }
  if (files.length === specs.length) ok(`${files.length} spec file(s) present with matching hashes`);

  // 3. Independent ESLint (incl. sf-locators/no-fragile-locators) + playwright --list (resolve, no execution).
  const lint = await runLint(root, files);
  const lintErrors = Object.entries(lint).flatMap(([f, e]) => e.map((x) => `${f} ${x}`));
  if (lintErrors.length) fail(`ESLint: ${lintErrors.slice(0, 5).join(' | ')}`);
  else ok(`ESLint clean on ${files.length} spec(s) (incl. sf-locators/no-fragile-locators)`);
  const list = await runList(root, files);
  const unlisted = specs.filter(
    (s) => !(list.byFile[s.path] ?? []).some((t) => s.testCaseIds.some((id) => t.startsWith(id))),
  );
  if (list.error) fail(`playwright --list: ${list.error}`);
  if (unlisted.length) fail(`not listed by playwright: ${unlisted.map((s) => s.path).join(', ')}`);
  else ok(`playwright test --list loads and lists ${specs.length}/${specs.length} spec(s) (nothing executed)`);
  const toolchain = existsSync(join(dir, 'toolchain.json'))
    ? (JSON.parse(readFileSync(join(dir, 'toolchain.json'), 'utf8')) as { typecheck: Record<string, string[]> })
    : undefined;
  const tscErrors = toolchain ? Object.values(toolchain.typecheck).flat() : undefined;
  if (!toolchain) fail('no toolchain.json (typecheck not recorded)');
  else if (tscErrors?.length) fail(`tsc errors at build time: ${tscErrors.slice(0, 3).join(' | ')}`);
  else ok('tsc: no errors in the generated specs at build time (run `pnpm typecheck` for the whole project)');

  // 4. Locator dry-run covers every member the specs use, all resolved.
  const used = [...new Set(specs.flatMap((s) => s.locatorsUsed))];
  if (!dry) fail('no locator dry-run recorded');
  else {
    const missingChecks = used.filter((u) => !dry.checks.some((c) => c.element === u && c.ok));
    if (missingChecks.length || dry.pageErrors.length)
      fail(`dry-run: unresolved ${missingChecks.join(', ')} ${dry.pageErrors.map((e) => e.error).join('; ')}`);
    else
      ok(
        `dry-run (${dry.environment}): ${used.length}/${used.length} used locators resolved (count 1, visible, enabled)`,
      );
  }

  // 5. Pass 2 settled; every spec has a verdict with reasons when not APPROVED.
  const open = findings.filter((f) => f.status === 'OPEN');
  const unjustified = findings.filter((f) => f.status === 'JUSTIFIED' && !f.resolution);
  if (open.length || unjustified.length)
    fail(`pass 2: ${open.length} OPEN, ${unjustified.length} JUSTIFIED without reason`);
  else ok(`pass 2: ${findings.length} finding(s), none open`);
  const noVerdict = specs.filter((s) => !s.reviewStatus || (s.reviewStatus !== 'APPROVED' && !s.reviewReasons.length));
  if (noVerdict.length) fail(`specs without a pass-2 verdict / reasons: ${noVerdict.map((s) => s.path).join(', ')}`);
  else {
    const n = (st: string): number => specs.filter((s) => s.reviewStatus === st).length;
    ok(`verdicts: ${n('APPROVED')} APPROVED, ${n('REVIEW_REQUIRED')} REVIEW_REQUIRED, ${n('BLOCKED')} BLOCKED`);
  }
}

function validateData(runId: string): void {
  const runDir = join(root, 'runs', runId);
  const dir = join(runDir, 'data');
  lines.push(`\n${runId} (${dir})`);
  const plan = parse(join(dir, 'data-plan.json'), DataPlan);
  const verify = parse(join(dir, 'verify.json'), z.array(RecordVerification));
  const negatives = parse(join(dir, 'negatives.json'), z.array(NegativeOutcome));
  const cleanup = parse(join(dir, 'cleanup-report.json'), CleanupReport);
  if (!plan || !verify || !negatives || !cleanup) return;
  lines.push(
    `  labels: ${plan.environment}, org ${plan.orgAlias}, recipe ${plan.recipe}@${plan.recipeHash}, run tag ${plan.runTag.field ?? 'name prefix'}=${plan.runTag.value}`,
  );
  if (!plan.valid) fail('plan is invalid');
  else ok(`plan valid: ${plan.steps.map((s) => s.object).join(' → ')} (${plan.negatives.length} negative variant(s))`);
  if (verify.length !== plan.steps.length || !verify.every((v) => v.ok))
    fail(
      `read-back verification: ${
        verify
          .filter((v) => !v.ok)
          .map((v) => v.stepId)
          .join(', ') || `${verify.length}/${plan.steps.length} verified`
      }`,
    );
  else
    ok(`created + verified by read-back: ${verify.map((v) => `${v.object} (${v.checks.length} fields)`).join(', ')}`);
  const parentChecks = verify.flatMap((v) =>
    v.checks.filter((c) => plan.steps.some((s) => s.stepId === v.stepId && s.parent?.field === c.field)),
  );
  if (parentChecks.length && parentChecks.every((c) => c.ok))
    ok(`lookups verified: ${parentChecks.map((c) => c.field).join(', ')}`);
  const badNeg = negatives.filter((n) => n.outcome !== 'REJECTED_AS_EXPECTED');
  if (badNeg.length || negatives.length !== plan.negatives.length)
    fail(`negatives: ${badNeg.map((n) => `${n.name}=${n.outcome}`).join(', ') || 'missing'}`);
  else
    ok(`negatives rejected as expected: ${negatives.map((n) => `${n.name} (${n.errorCodes.join(', ')})`).join(', ')}`);
  const deleted = cleanup.entries.filter((e) => e.action === 'DELETED' || e.action === 'ALREADY_GONE');
  if (cleanup.status !== 'CLEAN' || cleanup.verify.remaining.length)
    fail(`cleanup ${cleanup.status}, ${cleanup.verify.remaining.length} remaining`);
  else
    ok(
      `cleanup CLEAN: ${deleted.map((e) => e.object).join(' → ')} (reverse order); re-query (${cleanup.verify.queries.length} queries) → 0 remaining`,
    );
  const order = cleanup.entries.map((e) => e.object);
  const createdOrder = plan.steps.map((s) => s.object);
  if (order.slice(-createdOrder.length).join() !== [...createdOrder].reverse().join())
    fail(`cleanup order ${order.join(' → ')} is not the reverse of ${createdOrder.join(' → ')}`);
  // Audit: every create/delete is ALLOWED then SUCCEEDED (write-ahead), no REFUSED.
  const audit = existsSync(join(runDir, 'audit.jsonl'))
    ? readFileSync(join(runDir, 'audit.jsonl'), 'utf8')
        .split(/\r?\n/)
        .filter(Boolean)
        .map((l) => AuditEntry.parse(JSON.parse(l)))
    : [];
  const mut = audit.filter((a) => a.action === 'mutate');
  const pairs = (tool: string): [number, number, number, number] => [
    mut.filter((a) => a.tool.endsWith(tool) && a.outcome === 'ALLOWED').length,
    mut.filter((a) => a.tool.endsWith(tool) && a.outcome === 'SUCCEEDED').length,
    mut.filter((a) => a.tool.endsWith(tool) && a.outcome === 'FAILED').length,
    mut.filter((a) => a.tool.endsWith(tool) && a.outcome === 'REFUSED').length,
  ];
  const [ca, cs, cf, cr] = pairs('create');
  const [da, ds, df, dr] = pairs('delete');
  if (!mut.length) fail(`no audit entries in ${join(runDir, 'audit.jsonl')}`);
  else if (cr || dr || da !== ds || df)
    fail(`audit: create ${ca}/${cs}/${cf}/${cr}, delete ${da}/${ds}/${df}/${dr} (allowed/succeeded/failed/refused)`);
  else
    ok(
      `audit.jsonl: ${ca} create(s) ALLOWED → ${cs} SUCCEEDED + ${cf} FAILED (negative), ${da} delete(s) ALLOWED → ${ds} SUCCEEDED, 0 REFUSED`,
    );
}

for (const r of runs) {
  if (data) validateData(r);
  else await validateBuild(r);
}
process.stdout.write(
  `${lines.join('\n')}\n\n${result.failed ? 'VALIDATION FAILED' : data ? 'all data outputs valid' : 'all build outputs valid'}\n`,
);
process.exit(result.failed ? 1 : 0);
