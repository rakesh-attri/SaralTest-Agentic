// build ⇄ review2 (PLAN.md §2, Phase 4): Test Generator → files (page objects + specs) → toolchain (tsc, ESLint,
// playwright --list) + locator dry-run → Test Reviewer pass 2 → regenerate cases with regenerable findings
// (≤ MAX_PASS2_ROUNDS) → QA Lead settlement. Specs are generated and checked, never executed here (Phase 5).
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Logger } from 'pino';
import type { DryRunReport, GeneratedArtifact } from '../core/schemas/generation.js';
import { isAutomatable } from '../core/schemas/testCase.js';
import type { ModelRouter } from '../models/router.js';
import type { Redactor } from '../security/redact.js';
import type { SkillLoader } from '../skills/skillLoader.js';
import type { GenerationContext } from '../agents/test-generator/context.js';
import { generateTests } from '../agents/test-generator/graph.js';
import { hashText, writePageObjects } from '../agents/test-generator/pageObjects.js';
import type { ToolchainResult } from '../agents/test-generator/toolchain.js';
import { MAX_PASS2_ROUNDS, reviewPass2Round, settlePass2, withoutJudge } from '../agents/test-reviewer/pass2.js';
import { createIssue } from '../core/issues.js';
import type { Issue } from '../core/schemas/index.js';
import { formatTypeScript } from '../util/format.js';
import type { QAGraphStateType, QAGraphUpdate } from './state.js';

export interface BuildInputs {
  ctx: GenerationContext;
  notes: string[];
}

/** Supplies the generation context (catalog, recipes, snapshot facts, personas) for a run. */
export type BuildHook = (s: Pick<QAGraphStateType, 'runId' | 'storyKey' | 'testCases'>) => Promise<BuildInputs>;

export interface BuildDeps {
  build: BuildHook;
  /** Repo root: generated files go to `<root>/tests/{generated,pages}`. */
  root: string;
  router?: ModelRouter;
  skills?: SkillLoader;
  redactor?: Redactor;
  logger: Logger;
  say: (m: string) => void;
  /** tsc + ESLint + playwright --list on the given repo-relative files. Absent → not checked (review notes it). */
  toolchain?: (files: string[]) => Promise<ToolchainResult>;
  /** Locator dry-run for these `<pageId>.<member>` refs. Absent (offline) → not run (review notes it). */
  dryRun?: (refs: string[]) => Promise<DryRunReport>;
  /**
   * Partial rebuild (`qa build --cases`): the run is seeded with only some cases. Other generated specs of the story
   * stay untouched and their manifest entries are kept; only the rebuilt cases' entries are replaced.
   */
  merge?: boolean;
  /**
   * Judge outage inside pass 2 (policy.yaml TRANSIENT: retry → fallback → escalate): waits before each retry. The
   * router's own chain is the provider fallback; after the last retry the round runs deterministic-only, nothing is
   * APPROVED and the manifest is still written. Default: policy `retry.backoffSeconds` [2, 8, 30].
   */
  judgeBackoffMs?: readonly number[];
}

const GENERATED_MARK = '// Generated by sf-qa-agent';
/** Mechanical skeletons (render.ts) are generated files too: removed with the others when the design moves on. */
const SKELETON_MARK = '// MECHANICAL skeleton for ';
export const isGeneratedSpec = (text: string): boolean =>
  text.startsWith(GENERATED_MARK) || text.startsWith(SKELETON_MARK);
const abs = (root: string, rel: string): string => join(root, ...rel.split('/'));

export const manifestPath = (storyKey: string): string => `tests/generated/${storyKey}/manifest.json`;

export function createBuildNode(d: BuildDeps): {
  build: (s: QAGraphStateType) => Promise<QAGraphUpdate>;
  review2: (s: QAGraphStateType) => Promise<QAGraphUpdate>;
} {
  const cache = new Map<string, BuildInputs>();
  const inputs = async (s: QAGraphStateType): Promise<BuildInputs> => {
    let i = cache.get(s.runId);
    if (!i) {
      i = await d.build({ runId: s.runId, storyKey: s.storyKey, testCases: s.testCases });
      cache.set(s.runId, i);
      for (const n of i.notes) d.say(n);
    }
    return i;
  };
  const write = (rel: string, text: string): void => {
    const f = abs(d.root, rel);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, text, 'utf8');
  };

  const build = async (s: QAGraphStateType): Promise<QAGraphUpdate> => {
    const { ctx } = await inputs(s);
    const mechanical = s.degradedNodes.includes('build') || !d.router;
    const first = s.buildRound === 0;
    const pageFiles: GeneratedArtifact[] = [];
    if (first) {
      const files = await writePageObjects(d.root, ctx.catalog, (f, text) => {
        mkdirSync(dirname(f), { recursive: true });
        writeFileSync(f, text, 'utf8');
      });
      for (const f of files)
        pageFiles.push({
          kind: f.kind,
          path: f.path,
          hash: f.hash,
          testCaseIds: [],
          locatorsUsed: [],
          dataBindings: [],
          origin: 'deterministic',
          reviewReasons: [],
        });
      // Old generated specs of this story that the current design no longer has are removed (generated files only);
      // in a partial rebuild, only the specs of cases now ruled manual-only.
      const dir = abs(d.root, `tests/generated/${ctx.storyKey}`);
      const manualIds = s.testCases.filter((c) => c.execution === 'manual').map((c) => c.id);
      if (existsSync(dir)) {
        for (const f of readdirSync(dir).filter((x) => x.endsWith('.spec.ts'))) {
          if (d.merge && !manualIds.some((id) => f.startsWith(`${id}-`))) continue;
          if (isGeneratedSpec(readFileSync(join(dir, f), 'utf8'))) rmSync(join(dir, f));
        }
      }
    }
    const regenerate = first ? undefined : new Set(Object.keys(s.buildFeedback));
    const cases = s.testCases.filter((c) => isAutomatable(c) && (!regenerate || regenerate.has(c.id)));
    d.say(
      first
        ? `Test Generator: ${cases.length} APPROVED case(s) of ${s.testCases.length}${mechanical ? ' (mechanical skeletons)' : ''}…`
        : `Test Generator: regenerating ${cases.map((c) => c.id).join(', ')} with reviewer findings…`,
    );
    const r = await generateTests(
      ctx,
      cases,
      {
        ...(d.router ? { router: d.router } : {}),
        ...(d.skills ? { skills: d.skills } : {}),
        ...(d.redactor ? { redactor: d.redactor } : {}),
        logger: d.logger,
      },
      mechanical ? 'mechanical' : 'llm',
      first ? {} : s.buildFeedback,
    );
    for (const spec of r.specs) {
      spec.text = await formatTypeScript(spec.text, abs(d.root, spec.path));
      spec.artifact.hash = hashText(spec.text);
      write(spec.path, spec.text);
      d.say(`  ${spec.artifact.origin === 'mechanical' ? 'skeleton' : 'generated'} ${spec.path}`);
    }
    const prior = first ? [] : s.buildSpecs.filter((x) => !r.specs.some((n) => n.caseId === x.caseId));
    const specs = [...prior, ...r.specs].sort((a, b) => a.caseId.localeCompare(b.caseId));

    let toolchain: ToolchainResult | undefined;
    if (d.toolchain && specs.length) {
      d.say('Checking generated files: tsc, ESLint (sf-locators), playwright test --list (no execution)…');
      toolchain = await d.toolchain(specs.map((x) => x.path));
      for (const e of toolchain.toolErrors) d.say(`  tool error: ${e}`);
    }
    let dryRun: DryRunReport | undefined;
    const refs = [...new Set(specs.flatMap((x) => x.artifact.locatorsUsed))].sort();
    if (d.dryRun && refs.length) {
      d.say(`Locator dry-run: ${refs.length} page-object member(s) as ${ctx.catalog.persona} (observe only)…`);
      dryRun = await d.dryRun(refs);
      d.say(
        `  dry-run ${dryRun.ok ? 'OK' : 'FAILED'}: ${dryRun.checks.filter((c) => c.ok).length}/${dryRun.checks.length} resolved`,
      );
    }
    const env =
      r.environment === 'NONE'
        ? s.buildEnvironment
        : r.environment === 'MOCK' || s.buildEnvironment === 'MOCK'
          ? 'MOCK'
          : 'LIVE';
    return {
      buildSpecs: specs,
      buildChecks: { ...(toolchain ? { toolchain } : {}), ...(dryRun ? { dryRun } : {}) },
      buildEnvironment: env,
      buildModels: [...new Set([...s.buildModels, ...r.models])],
      buildRound: s.buildRound + 1,
      generated: first ? pageFiles : s.generated.filter((g) => g.kind !== 'spec'),
      notes: r.degraded.map((x) => `Test Generator degraded ${x.caseId}: ${x.reason}`),
    };
  };

  const review2 = async (s: QAGraphStateType): Promise<QAGraphUpdate> => {
    const { ctx } = await inputs(s);
    const specs = s.buildSpecs;
    const round = s.pass2Round + 1;
    const mechanical = s.degradedNodes.includes('review2') || !d.router;
    const backoff = d.judgeBackoffMs ?? [2000, 8000, 30000];
    const issues: Issue[] = [];
    let r: Awaited<ReturnType<typeof reviewPass2Round>> | undefined;
    for (let attempt = 0; ; attempt++) {
      r = await reviewPass2Round(
        {
          ctx,
          cases: s.testCases,
          specs,
          ...(s.buildChecks.toolchain ? { toolchain: s.buildChecks.toolchain } : {}),
          ...(s.buildChecks.dryRun ? { dryRun: s.buildChecks.dryRun } : {}),
          prior: s.pass2Findings,
          round,
          mode: mechanical ? 'mechanical' : 'llm',
          transientDegrades: true,
        },
        {
          ...(d.router ? { router: d.router } : {}),
          ...(d.skills ? { skills: d.skills } : {}),
          ...(d.redactor ? { redactor: d.redactor } : {}),
          logger: d.logger,
        },
      );
      const wait = backoff[attempt];
      if (r.judgeError?.kind !== 'TRANSIENT' || wait === undefined) break;
      d.say(
        `  judge unavailable (${r.judgeError.message.slice(0, 120)}) — retry ${attempt + 1}/${backoff.length} in ${Math.round(wait / 1000)} s`,
      );
      await new Promise((res) => setTimeout(res, wait));
    }
    if (r.judgeError) {
      issues.push(
        createIssue({
          kind: r.judgeError.kind === 'TRANSIENT' ? 'TRANSIENT' : 'INVALID_LLM_OUTPUT',
          node: 'review2',
          message: `pass 2 judge unavailable after retries and provider fallback: ${r.judgeError.message.slice(0, 300)}`,
          resolution: 'DEGRADED',
        }),
      );
    }
    const open = r.findings.filter((f) => f.status === 'OPEN');
    d.say(
      `Test Reviewer pass 2, round ${round}: ${r.findings.length} finding(s), ${open.length} open${r.judgeDegraded ? ' (judge unavailable: deterministic only)' : ''}.`,
    );
    const regenerable = Object.keys(r.feedback).length > 0;
    const models = [...new Set([...s.buildModels, ...r.models])];
    if (round < MAX_PASS2_ROUNDS && regenerable && !mechanical) {
      return { pass2Findings: r.findings, pass2Round: round, buildFeedback: r.feedback, buildModels: models, issues };
    }
    const settled0 = settlePass2(r.findings, specs);
    // Without the judge nothing is APPROVED; the manifest is still written (every path ends with an honest status).
    const settled =
      r.judgeDegraded && !mechanical ? { ...settled0, artifacts: withoutJudge(settled0.artifacts) } : settled0;
    const counts = (st: string): number => settled.artifacts.filter((a) => a.reviewStatus === st).length;
    d.say(
      `Pass 2 settled: ${counts('APPROVED')} APPROVED, ${counts('REVIEW_REQUIRED')} REVIEW_REQUIRED, ${counts('BLOCKED')} BLOCKED.`,
    );
    // Manifest next to the specs (checked in; `qa locators dry-run --manifest` reads it). A partial rebuild keeps the
    // entries of the cases it did not rebuild (with the build run that produced them).
    const rebuilt = new Set(settled.artifacts.flatMap((a) => a.testCaseIds));
    const manifestFile = abs(d.root, manifestPath(ctx.storyKey));
    const kept =
      d.merge && existsSync(manifestFile)
        ? (JSON.parse(readFileSync(manifestFile, 'utf8')) as {
            artifacts?: (GeneratedArtifact & { buildRun?: string })[];
            buildRun?: string;
          })
        : undefined;
    const manual = s.testCases
      .filter((c) => c.execution === 'manual')
      .map((c) => ({ caseId: c.id, reason: c.executionReason ?? 'manual-only' }));
    const keptArtifacts = (kept?.artifacts ?? [])
      .filter(
        (a) => a.kind === 'spec' && !a.testCaseIds.some((id) => rebuilt.has(id) || manual.some((m) => m.caseId === id)),
      )
      .map((a) => ({ ...a, buildRun: a.buildRun ?? kept?.buildRun }));
    const artifacts = [...keptArtifacts, ...settled.artifacts.map((a) => ({ ...a, buildRun: s.runId }))].sort((a, b) =>
      a.path.localeCompare(b.path),
    );
    write(
      manifestPath(ctx.storyKey),
      `${JSON.stringify({ storyKey: ctx.storyKey, designRun: ctx.designRunId, buildRun: s.runId, org: ctx.orgAlias, environment: ctx.environment, artifacts, manualOnly: manual }, null, 2)}\n`,
    );
    return {
      pass2Findings: settled.findings,
      pass2Round: round,
      buildFeedback: {},
      buildModels: models,
      generated: [...s.generated.filter((g) => g.kind !== 'spec'), ...settled.artifacts],
      issues,
    };
  };

  return { build, review2 };
}
