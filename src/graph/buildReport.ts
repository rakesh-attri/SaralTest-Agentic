// Build outputs (runs/<runId>/build/): manifest, pass-2 findings, toolchain + dry-run results, IR per case, and a
// Markdown + HTML build report. MOCK / mechanical / FIXTURE are labelled everywhere (CLAUDE.md rule 13).
import { esc, md } from '../report/format.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { A11Y_SCOPE_NOTE } from '../agents/test-generator/render.js';
import { isAutomatable } from '../core/schemas/testCase.js';
import type { QAGraphStateType } from './state.js';


export interface BuildSummary {
  runId: string;
  storyKey?: string;
  designRunId?: string;
  status: string;
  buildEnvironment: 'LIVE' | 'MOCK' | 'NONE';
  orgEnvironment: 'LIVE' | 'FIXTURE' | 'NONE';
  models: string[];
  approvedCases: number;
  /** APPROVED cases ruled manual-only: no spec, RTM lists them as manual. */
  manualCases: string[];
  specs: { caseId: string; path: string; origin: string; reviewStatus?: string; reasons: string[]; locators: number }[];
  counts: { APPROVED: number; REVIEW_REQUIRED: number; BLOCKED: number };
  pass2: { rounds: number; findings: number; open: number; resolved: number; justified: number; escalated: number };
  toolchain?: { typecheckErrors: number; lintErrors: number; listed: number; toolErrors: string[] };
  dryRun?: { ok: boolean; resolved: number; checked: number; environment: string; persona: string };
}

export function summarizeBuild(s: QAGraphStateType, status: string): BuildSummary {
  const specs = s.generated.filter((g) => g.kind === 'spec');
  const tc = s.buildChecks.toolchain;
  const dr = s.buildChecks.dryRun;
  const n = (st: string): number => specs.filter((a) => a.reviewStatus === st).length;
  return {
    runId: s.runId,
    ...(s.storyKey ? { storyKey: s.storyKey } : {}),
    ...(s.designRunId ? { designRunId: s.designRunId } : {}),
    status,
    buildEnvironment: s.buildEnvironment,
    orgEnvironment: s.orgEnvironment,
    models: s.buildModels,
    approvedCases: s.testCases.filter(isAutomatable).length,
    manualCases: s.testCases.filter((c) => c.reviewStatus === 'APPROVED' && c.execution === 'manual').map((c) => c.id),
    specs: specs.map((a) => ({
      caseId: a.testCaseIds[0] ?? '',
      path: a.path,
      origin: a.origin,
      ...(a.reviewStatus ? { reviewStatus: a.reviewStatus } : {}),
      reasons: a.reviewReasons,
      locators: a.locatorsUsed.length,
    })),
    counts: { APPROVED: n('APPROVED'), REVIEW_REQUIRED: n('REVIEW_REQUIRED'), BLOCKED: n('BLOCKED') },
    pass2: {
      rounds: s.pass2Round,
      findings: s.pass2Findings.length,
      open: s.pass2Findings.filter((f) => f.status === 'OPEN').length,
      resolved: s.pass2Findings.filter((f) => f.status === 'RESOLVED').length,
      justified: s.pass2Findings.filter((f) => f.status === 'JUSTIFIED').length,
      escalated: s.pass2Findings.filter((f) => f.escalated).length,
    },
    ...(tc
      ? {
          toolchain: {
            typecheckErrors: Object.values(tc.typecheck).flat().length,
            lintErrors: Object.values(tc.lint).flat().length,
            listed: Object.values(tc.listed).filter((v) => v.length).length,
            toolErrors: tc.toolErrors,
          },
        }
      : {}),
    ...(dr
      ? {
          dryRun: {
            ok: dr.ok,
            resolved: dr.checks.filter((c) => c.ok).length,
            checked: dr.checks.length,
            environment: dr.environment,
            persona: dr.persona,
          },
        }
      : {}),
  };
}

function banners(s: QAGraphStateType): string[] {
  const out: string[] = [];
  if (s.buildEnvironment === 'MOCK')
    out.push('> **MOCK** — the tests were generated by the mock model provider. Not real generator output.');
  if (s.buildEnvironment === 'NONE')
    out.push('> **MECHANICAL** — no model answered: specs are `test.fixme` skeletons for a human.');
  if (s.orgEnvironment === 'FIXTURE' || s.buildChecks.dryRun?.environment === 'FIXTURE') {
    out.push('> **FIXTURE** — page objects / dry-run come from the offline fixture, not Salesforce.');
  }
  return out;
}

export function renderBuildReport(s: QAGraphStateType, status: string): string {
  const sum = summarizeBuild(s, status);
  const L: string[] = [];
  L.push(`# Test build — ${sum.storyKey ?? sum.runId}`, '');
  L.push(
    `Run \`${sum.runId}\` · status **${status}** · design run \`${sum.designRunId ?? '-'}\` · generator/judge: ${sum.models.join(', ') || 'none (mechanical)'}`,
  );
  const b = banners(s);
  if (b.length) L.push('', ...b);
  L.push(
    '',
    `Generated and checked only — **not executed** (execution is Phase 5). ${sum.approvedCases} APPROVED case(s) → ${sum.specs.length} spec(s): **${sum.counts.APPROVED} APPROVED · ${sum.counts.REVIEW_REQUIRED} REVIEW_REQUIRED · ${sum.counts.BLOCKED} BLOCKED**.${sum.manualCases.length ? ` Manual-only (no spec): ${sum.manualCases.join(', ')}.` : ''}`,
    '',
    '## Checks',
    '',
    '| Check | Result |',
    '|---|---|',
    `| TypeScript (tsc) | ${sum.toolchain ? `${sum.toolchain.typecheckErrors} error(s) in generated specs` : 'not run'} |`,
    `| ESLint incl. sf-locators/no-fragile-locators | ${sum.toolchain ? `${sum.toolchain.lintErrors} error(s)` : 'not run'} |`,
    `| playwright test --list (resolve, no execution) | ${sum.toolchain ? `${sum.toolchain.listed}/${sum.specs.length} spec(s) listed` : 'not run'} |`,
    `| Locator dry-run | ${sum.dryRun ? `${sum.dryRun.ok ? 'OK' : 'FAILED'} — ${sum.dryRun.resolved}/${sum.dryRun.checked} resolved (${sum.dryRun.environment}, persona ${sum.dryRun.persona})` : 'not run (offline)'} |`,
    `| Test Reviewer pass 2 | ${sum.pass2.rounds} round(s), ${sum.pass2.findings} finding(s): ${sum.pass2.resolved} resolved, ${sum.pass2.justified} settled (${sum.pass2.escalated} escalated), **${sum.pass2.open} open** |`,
  );
  if (sum.toolchain?.toolErrors.length) L.push('', ...sum.toolchain.toolErrors.map((e) => `- tool error: ${md(e)}`));
  L.push('', '## Specs', '', '| Case | Spec | Origin | Pass 2 | Locators | Reasons |', '|---|---|---|---|---|---|');
  for (const x of sum.specs) {
    L.push(
      `| ${x.caseId} | \`${x.path}\` | ${x.origin} | **${x.reviewStatus ?? '-'}** | ${x.locators} | ${md(x.reasons.join('; ')) || '—'} |`,
    );
  }
  const notes = (s.buildSpecs as { ir?: { notes: string[] }; caseId: string }[]).flatMap((x) =>
    (x.ir?.notes ?? []).map((n) => `${x.caseId}: ${n}`),
  );
  if (notes.length || s.buildSpecs.some((x) => x.text.includes('a11y scope rule'))) {
    L.push('', '## Generator notes (substitutions, scope rules)', '');
    for (const n of notes) L.push(`- ${md(n)}`);
    if (s.buildSpecs.some((x) => x.text.includes('a11y scope rule'))) L.push(`- ${A11Y_SCOPE_NOTE}`);
  }
  if (s.pass2Findings.length) {
    L.push(
      '',
      '## Test Reviewer pass 2 findings',
      '',
      '| Id | Sev | Rule | Cases | Status | Finding | Resolution |',
      '|---|---|---|---|---|---|---|',
    );
    for (const f of s.pass2Findings) {
      L.push(
        `| ${f.id} | ${f.severity} | ${f.rule} | ${f.caseIds.join(', ')} | ${f.status}${f.escalated ? ' (escalated)' : ''} | ${md(f.text)} | ${md(f.resolution ?? '')} |`,
      );
    }
  }
  const attempts = s.buildSpecs.flatMap((x) => (x.attempts ?? []).map((a) => ({ caseId: x.caseId, ...a })));
  if (attempts.length) {
    L.push(
      '',
      '## Model attempts (last build round per case)',
      '',
      '| Case | Model | Attempt | Outcome | Problems / error |',
      '|---|---|---|---|---|',
    );
    for (const a of attempts) {
      L.push(
        `| ${a.caseId} | ${a.model} | ${a.attempt} | ${a.outcome}${a.status ? ` (HTTP ${String(a.status)})` : ''} | ${md((a.providerMessage ? [a.providerMessage] : (a.problems ?? []).slice(0, 3)).join(' · ').slice(0, 800))} |`,
      );
    }
  }
  const dr = s.buildChecks.dryRun;
  if (dr) {
    L.push(
      '',
      `## Locator dry-run (${dr.environment}, persona ${dr.persona}, ${dr.at})`,
      '',
      '| Element | Count | Visible | Enabled | Result | Note |',
      '|---|---|---|---|---|---|',
    );
    for (const c of dr.checks)
      L.push(
        `| ${c.element} | ${c.count} | ${c.visible ? 'yes' : 'no'} | ${c.enabled ? 'yes' : 'no'} | ${c.ok ? 'ok' : '**FAIL**'} | ${md(c.note ?? '')} |`,
      );
    for (const e of dr.pageErrors) L.push(`| ${e.page} (page) | — | — | — | **FAIL** | ${md(e.error)} |`);
  }
  L.push('');
  return L.join('\n');
}

export function renderBuildHtml(s: QAGraphStateType, status: string): string {
  const sum = summarizeBuild(s, status);
  const row = (cells: string[]): string => `<tr>${cells.map((c) => `<td>${c}</td>`).join('')}</tr>`;
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Test build ${esc(sum.storyKey ?? sum.runId)}</title>
<style>body{font-family:system-ui,sans-serif;margin:24px;max-width:1200px}table{border-collapse:collapse;width:100%;margin:12px 0}td,th{border:1px solid #ccc;padding:4px 8px;text-align:left;vertical-align:top;font-size:13px}.b{background:#fff3cd;padding:8px;border-left:4px solid #e0a800}.APPROVED{color:#18794e}.REVIEW_REQUIRED{color:#b54708}.BLOCKED{color:#b42318}</style></head><body>
<h1>Test build — ${esc(sum.storyKey ?? sum.runId)}</h1>
<p>Run <code>${esc(sum.runId)}</code> · status <b>${esc(status)}</b> · design run <code>${esc(sum.designRunId ?? '-')}</code> · ${esc(sum.models.join(', ') || 'mechanical')}</p>
${banners(s)
  .map((b) => `<p class="b">${esc(b.replace(/^> /, '').replace(/\*\*/g, ''))}</p>`)
  .join('\n')}
<p>Generated and checked only — not executed (Phase 5). <b class="APPROVED">${sum.counts.APPROVED} APPROVED</b> · <b class="REVIEW_REQUIRED">${sum.counts.REVIEW_REQUIRED} REVIEW_REQUIRED</b> · <b class="BLOCKED">${sum.counts.BLOCKED} BLOCKED</b></p>
<table><tr><th>Case</th><th>Spec</th><th>Origin</th><th>Pass 2</th><th>Reasons</th></tr>
${sum.specs.map((x) => row([esc(x.caseId), `<code>${esc(x.path)}</code>`, esc(x.origin), `<b class="${esc(x.reviewStatus ?? '')}">${esc(x.reviewStatus ?? '-')}</b>`, esc(x.reasons.join('; '))])).join('\n')}</table>
<h2>Pass 2 findings</h2><table><tr><th>Id</th><th>Sev</th><th>Rule</th><th>Cases</th><th>Status</th><th>Finding</th><th>Resolution</th></tr>
${s.pass2Findings.map((f) => row([f.id, f.severity, esc(f.rule), esc(f.caseIds.join(', ')), esc(f.status + (f.escalated ? ' (escalated)' : '')), esc(f.text), esc(f.resolution ?? '')])).join('\n')}</table>
</body></html>
`;
}

export async function writeBuildReport(s: QAGraphStateType, runDir: string, status: string): Promise<string[]> {
  const dir = join(runDir, 'build');
  await mkdir(join(dir, 'ir'), { recursive: true });
  const out: string[] = [];
  const put = async (name: string, text: string): Promise<void> => {
    const f = join(dir, name);
    await writeFile(f, text, 'utf8');
    out.push(f);
  };
  await put('build-run.json', `${JSON.stringify(summarizeBuild(s, status), null, 2)}\n`);
  await put(
    'manifest.json',
    `${JSON.stringify({ storyKey: s.storyKey, designRun: s.designRunId, buildRun: s.runId, artifacts: s.generated }, null, 2)}\n`,
  );
  await put('review-pass2.json', `${JSON.stringify(s.pass2Findings, null, 2)}\n`);
  if (s.buildChecks.toolchain) await put('toolchain.json', `${JSON.stringify(s.buildChecks.toolchain, null, 2)}\n`);
  await put(
    'model-attempts.json',
    `${JSON.stringify(
      s.buildSpecs.map((x) => ({
        caseId: x.caseId,
        model: x.model,
        origin: x.artifact.origin,
        attempts: x.attempts ?? [],
      })),
      null,
      2,
    )}
`,
  );
  if (s.buildChecks.dryRun) await put('dry-run.json', `${JSON.stringify(s.buildChecks.dryRun, null, 2)}\n`);
  for (const x of s.buildSpecs)
    if (x.ir) await put(join('ir', `${x.caseId}.json`), `${JSON.stringify(x.ir, null, 2)}\n`);
  await put('build-report.md', renderBuildReport(s, status));
  await put('build-report.html', renderBuildHtml(s, status));
  return out;
}
